// Builds src/locales/zh-TW.ts: every Simplified Chinese string literal in the frontend
// (plus web API errors from the backend) converted to Traditional Chinese (Taiwan).
// Template slots `${...}` and Go format verbs become {0}, {1}… so runtime text still matches.
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Converter } from "opencc-js/cn2t";

const twp = Converter({ from: "cn", to: "twp" });
// twp turns 循环 into the programming term 迴圈; in DeFi it means a leverage loop.
const toTW = (s) => twp(s).replaceAll("迴圈", "循環");
const han = /\p{Script=Han}/u;

function walk(dir, out = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) {
      if (f !== "locales") walk(p, out);
    } else if (/\.tsx?$/.test(f)) out.push(p);
  }
  return out;
}

const keys = new Set();

const tsLiteral = /"((?:[^"\\\n]|\\.)*)"|'((?:[^'\\\n]|\\.)*)'|`((?:[^`\\]|\\.)*)`/g;
for (const file of walk("src")) {
  const src = readFileSync(file, "utf8").replace(/^\s*\/\/.*$/gm, "");
  for (const m of src.matchAll(tsLiteral)) {
    let text;
    if (m[3] !== undefined) {
      let i = 0;
      text = m[3].replace(/\$\{[^}]*\}/g, () => `{${i++}}`);
      text = text.replace(/\\`/g, "`").replace(/\\n/g, "\n");
    } else {
      text = JSON.parse(`"${(m[1] ?? m[2]).replace(/\\'/g, "'")}"`);
    }
    if (han.test(text)) keys.add(text);
  }
}

const goLiteral = /"((?:[^"\\\n]|\\.)*)"/g;
for (const m of readFileSync("../backend/internal/web/server.go", "utf8").matchAll(goLiteral)) {
  let i = 0;
  const text = JSON.parse(`"${m[1]}"`).replace(/%[-+# 0-9.]*[dsvfqx]/g, () => `{${i++}}`);
  if (han.test(text)) keys.add(text);
}

const dict = {};
for (const k of [...keys].sort()) {
  const v = toTW(k);
  if (v !== k) dict[k] = v;
}

writeFileSync(
  "src/locales/zh-TW.ts",
  "// Generated by scripts/gen-zh-tw.mjs. Do not edit.\n" +
    "const zhTW: Record<string, string> = " +
    JSON.stringify(dict, null, 2) +
    ";\n\nexport default zhTW;\n",
);
console.log(`zh-TW: ${Object.keys(dict).length} entries`);
